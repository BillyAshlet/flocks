const KEY = 'echo-lang';

export class I18n {
  constructor() {
    // flocks: the site is English; the stored choice from the original page
    // is ignored.
    this.lang = 'en';
    this.listeners = [];
  }

  // t('range') 取字符串；t('hintFollow', 3) 取带参数的
  t(key, ...args) {
    const v = DICT[this.lang][key];
    return typeof v === 'function' ? v(...args) : (v ?? key);
  }

  set(lang) {
    if (!LANGS.includes(lang) || lang === this.lang) return;
    this.lang = lang;
    try {
      localStorage.setItem(KEY, lang);
    } catch { /* storage unavailable */ }
    for (const fn of this.listeners) fn(lang);
  }

  onChange(fn) {
    this.listeners.push(fn);
  }
}
